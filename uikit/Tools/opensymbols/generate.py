#!/usr/bin/env python3
"""Generate OpenUIKit's open symbol catalog from mapping.tsv and Phosphor Icons.

Usage:
  python3 -I generate.py --phosphor <unpacked @phosphor-icons/core package dir> \
      --out ../../Sources/OpenUIKit/OpenSymbols/OpenSymbolCatalog.generated.swift

Only the SVG path data of glyphs the mapping references is emitted. The
package version is read from its package.json and must equal PHOSPHOR_VERSION;
bump both together. Fails on any unknown glyph, malformed row or SVG element
other than <svg>/<path d>.
"""
import argparse
import json
import pathlib
import re
import sys

PHOSPHOR_VERSION = "2.1.1"
COMPOSITES = {"-": "none", "ring": "ring", "disc": "disc", "mirror": "mirror", "badge-plus": "badgePlus"}
PATH_RE = re.compile(r'<path d="([^"]+)"/>')
D_CHARS = re.compile(r"^[MmLlHhVvCcSsQqTtAaZz0-9eE.,+\- ]+$")


def die(msg):
    sys.exit("generate.py: " + msg)


def glyph_file(assets, icon, weight):
    if weight in ("regular", "regular-only"):
        return assets / "regular" / (icon + ".svg"), icon
    if weight == "bold":
        return assets / "bold" / (icon + "-bold.svg"), icon + "-bold"
    return assets / "fill" / (icon + "-fill.svg"), icon + "-fill"


def load_paths(path):
    if not path.is_file():
        die("missing glyph " + str(path))
    text = path.read_text()
    paths = PATH_RE.findall(text)
    stripped = PATH_RE.sub("", text)
    if not paths or not re.fullmatch(
        r'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor"></svg>\s*',
        stripped,
    ):
        die("unexpected SVG structure in " + str(path))
    for d in paths:
        if not D_CHARS.match(d):
            die("unexpected path data characters in " + str(path))
    return paths


def swift_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phosphor", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--mapping", default=str(pathlib.Path(__file__).with_name("mapping.tsv")))
    args = ap.parse_args()

    pkg = pathlib.Path(args.phosphor)
    version = json.loads((pkg / "package.json").read_text())["version"]
    if version != PHOSPHOR_VERSION:
        die("Phosphor package is %s, generator pins %s" % (version, PHOSPHOR_VERSION))
    assets = pkg / "assets"

    entries = []
    seen = set()
    glyphs = {}
    bold_icons = set()
    single_icons = set()
    for lineno, line in enumerate(pathlib.Path(args.mapping).read_text().splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) not in (4, 5):
            die("mapping.tsv:%d: expected 4 or 5 tab-separated columns" % lineno)
        name, icon, weight, composite = cols[:4]
        note = cols[4] if len(cols) == 5 else ""
        if name in seen:
            die("mapping.tsv:%d: duplicate %s" % (lineno, name))
        seen.add(name)
        if weight not in ("regular", "regular-only", "fill") or composite not in COMPOSITES:
            die("mapping.tsv:%d: bad weight or composite" % lineno)
        if composite == "badge-plus" and icon != "user":
            die("mapping.tsv:%d: badge-plus is drawn from primitives; its icon must be user" % lineno)
        path, key = glyph_file(assets, icon, weight)
        glyphs[key] = load_paths(path)
        # Regular-weight entries also carry Phosphor's bold drawing, which
        # OpenSymbols uses for SF semibold and heavier (fill has one weight).
        if weight == "regular":
            bpath, bkey = glyph_file(assets, icon, "bold")
            glyphs[bkey] = load_paths(bpath)
            bold_icons.add(icon)
        elif weight == "regular-only":
            single_icons.add(icon)
        if bold_icons & single_icons:
            die("mapping.tsv:%d: %s is both regular and regular-only" % (lineno, icon))
        if composite in ("ring", "disc"):
            bpath, bkey = glyph_file(assets, "circle", "regular" if composite == "ring" else "fill")
            glyphs[bkey] = load_paths(bpath)
            if composite == "ring":
                bpath, bkey = glyph_file(assets, "circle", "bold")
                glyphs[bkey] = load_paths(bpath)
        entries.append((name, key, COMPOSITES[composite], note))

    entries.sort()
    out = []
    out.append("// GENERATED by uikit/Tools/opensymbols/generate.py from")
    out.append("// uikit/Tools/opensymbols/mapping.tsv and Phosphor Icons %s" % PHOSPHOR_VERSION)
    out.append("// (@phosphor-icons/core, https://github.com/phosphor-icons/core). Do not edit.")
    out.append("//")
    out.append("// Phosphor Icons is MIT licensed, Copyright (c) 2023 Phosphor Icons; the licence")
    out.append("// text is uikit/THIRD_PARTY_LICENSES/PhosphorIcons-LICENSE. These are open glyphs")
    out.append("// chosen by SF Symbol name; no SF Symbols artwork is copied.")
    out.append("")
    out.append("enum _OpenSymbolCatalog {")
    out.append("    static let phosphorVersion = %s" % swift_string(PHOSPHOR_VERSION))
    out.append("")
    out.append("    /// Every mapped SF Symbol name, sorted.")
    out.append("    static let names: [String] = [")
    for name, _, _, _ in entries:
        out.append("        %s," % swift_string(name))
    out.append("    ]")
    out.append("")
    out.append("    static func entry(_ name: String) -> _OpenSymbolEntry? {")
    out.append("        switch name {")
    for name, key, composite, note in entries:
        suffix = "  // approximation: " + note if note else ""
        out.append("        case %s: return _OpenSymbolEntry(glyph: %s, composite: .%s)%s"
                   % (swift_string(name), swift_string(key), composite, suffix))
    out.append("        default: return nil")
    out.append("        }")
    out.append("    }")
    out.append("")
    out.append("    /// SVG path data (256-unit viewBox, nonzero fill) per Phosphor glyph.")
    out.append("    static func pathData(_ glyph: String) -> [String]? {")
    out.append("        switch glyph {")
    for key in sorted(glyphs):
        body = ", ".join(swift_string(d) for d in glyphs[key])
        out.append("        case %s: return [%s]" % (swift_string(key), body))
    out.append("        default: return nil")
    out.append("        }")
    out.append("    }")
    out.append("}")
    pathlib.Path(args.out).write_text("\n".join(out) + "\n")
    print("generate.py: %d names, %d glyphs -> %s" % (len(entries), len(glyphs), args.out))


if __name__ == "__main__":
    main()
