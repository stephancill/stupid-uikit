#!/usr/bin/env python3
"""Regenerate OpenUIKit's SF Symbol accessibility label table from an iOS Simulator runtime.

iOS names an SF Symbol image for accessibility from three string tables in
AccessibilitySharedSupport.framework/<lang>.lproj, consulted in this order:

    SymbolNameOverrides.strings       hand-written ("xmark" -> "Close")
    SymbolNamesAutoGenerated.strings  role names ("star.fill" -> "favourite")
    SymbolNamesLastResort.strings     shape descriptions ("arrow.up.forward.square" ->
                                      "Up-forward arrow in a square")

and capitalises every word of the result (words split at spaces and hyphens). The order and the
capitalisation were checked against the iOS 27.0 references' `stupidsim ui-tree` output, one
symbol per table: "Close" (xmark, override), "Volume High" (speaker.wave.2.fill) and "Favourite"
(star.fill, auto-generated, en_GB), "Up-Forward Arrow In A Square" (arrow.up.forward.square, last
resort).

This script runs on a Mac with the iOS Simulator runtime installed (the user's own Xcode
download). It reads only the names listed in --names (the symbols an app uses) and writes a Swift
table with those labels; Apple's tables themselves are never copied into the repository.

A name is left unlabelled (and listed in the output's header) when the lookup is ambiguous:
  - the name is a legacy alias (CoreGlyphs name_aliases.strings): iOS may resolve the alias first;
  - only the last-resort table has the name while its unfilled form (".fill" removed) has an
    override or auto-generated label: iOS may fold the fill variant first;
  - no table has it.

Usage:
  sf_symbol_labels_from_runtime.py --runtime "<iOS 27.0.simruntime>/Contents/Resources/RuntimeRoot" \
      --names uikit/scripts/sf_symbol_label_names.txt --languages en,en_GB \
      --out uikit/Sources/OpenUIKit/Automation/SymbolAccessibilityLabels.swift
"""

import argparse
import plistlib
import re
import sys
from pathlib import Path

TABLES = ["SymbolNameOverrides", "SymbolNamesAutoGenerated", "SymbolNamesLastResort"]


def load(path: Path) -> dict:
    with path.open("rb") as f:
        return plistlib.load(f)


def capitalise(text: str) -> str:
    # Foundation's `capitalized`: the first letter of every word upper-cased, the rest lower-cased;
    # words split at whitespace and hyphens ("Up-forward arrow" -> "Up-Forward Arrow").
    return re.sub(r"[^\s\-]+", lambda m: m.group(0)[:1].upper() + m.group(0)[1:].lower(), text)


def swift_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runtime", required=True, type=Path, help="the runtime's RuntimeRoot")
    parser.add_argument("--names", required=True, type=Path)
    parser.add_argument("--languages", default="en,en_GB")
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()

    private = args.runtime / "System/Library/PrivateFrameworks"
    ax = private / "AccessibilitySharedSupport.framework"
    glyphs = private / "SFSymbols.framework/CoreGlyphs.bundle"
    system = load(args.runtime / "System/Library/CoreServices/SystemVersion.plist")
    version = f"{system['ProductVersion']} ({system['ProductBuildVersion']})"
    for required in [ax, glyphs]:
        if not required.is_dir():
            sys.exit(f"sf_symbol_labels: {required} is missing; pass the simulator runtime's RuntimeRoot")
    available = load(glyphs / "name_availability.plist")["symbols"]
    aliases = load(glyphs / "name_aliases.strings")

    names = [line.strip() for line in args.names.read_text().splitlines()
             if line.strip() and not line.startswith("#")]
    unknown = [n for n in names if n not in available and n not in aliases]
    if unknown:
        sys.exit(f"sf_symbol_labels: not SF Symbol names in this runtime: {', '.join(unknown)}")

    languages = args.languages.split(",")
    labels: dict = {}
    skipped: dict = {}
    for language in languages:
        tables = [load(ax / f"{language}.lproj" / f"{t}.strings") for t in TABLES]
        labels[language] = {}
        for name in names:
            hits = [(i, t[name]) for i, t in enumerate(tables) if name in t]
            base = name[: -len(".fill")] if name.endswith(".fill") else None
            if name in aliases:
                skipped.setdefault(name, f"legacy alias of {aliases[name]}")
                continue
            if not hits:
                skipped.setdefault(name, "no label in any table")
                continue
            if hits[0][0] == 2 and base and any(base in t for t in tables[:2]):
                skipped.setdefault(name, f"last-resort only; {base} has a role label")
                continue
            labels[language][name] = capitalise(hits[0][1])
    base_language = languages[0]
    lines = [
        "// Generated by uikit/scripts/sf_symbol_labels_from_runtime.py from the iOS "
        f"{version} Simulator runtime's",
        "// AccessibilitySharedSupport symbol name tables, for the names in",
        "// uikit/scripts/sf_symbol_label_names.txt. Do not edit; see uikit/docs/SYMBOL_ACCESSIBILITY_LABELS.md.",
        "//",
        "// Left unlabelled (ambiguous lookup):",
    ]
    for name in sorted(skipped):
        lines.append(f"//   {name}: {skipped[name]}")
    lines += [
        "",
        "enum _SymbolAccessibilityLabelTable {",
        f"    /// `{base_language}.lproj`.",
        "    static let base: [String: String] = [",
    ]
    for name in sorted(labels[base_language]):
        lines.append(f"        {swift_string(name)}: {swift_string(labels[base_language][name])},")
    lines += ["    ]", "", "    /// Regional tables: only the entries that differ from `base`.",
              "    static let regional: [String: [String: String]] = ["]
    for language in languages[1:]:
        diff = {n: v for n, v in labels[language].items() if labels[base_language].get(n) != v}
        missing = [n for n in labels[base_language] if n not in labels[language]]
        if missing:
            sys.exit(f"sf_symbol_labels: {language} lacks labels {missing} that {base_language} has")
        lines.append(f"        {swift_string(language)}: [")
        for name in sorted(diff):
            lines.append(f"            {swift_string(name)}: {swift_string(diff[name])},")
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    args.out.write_text("\n".join(lines))
    print(f"sf_symbol_labels: {len(labels[base_language])} labelled, {len(skipped)} left unlabelled -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
